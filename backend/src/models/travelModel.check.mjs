import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { syncVehicleApprovalTokens, plannedTravelDateTime, isTravelQrAvailable, isTravelQrReadable, autoCloseTravels } from './travelModel.js';

const valid = 'abcdefabcdefabcdefabcdefabcdefabcdefabcdefabcdef';
const tokens = [{ nip: '1', token: 'a', statusId: 1 }, { nip: '2', token: 'b', statusId: 1 }, { nip: '3', token: 'c', statusId: 1 }];
assert.deepEqual(syncVehicleApprovalTokens(tokens, 3, '1', '2026-10-30T00:00:00.000Z'), tokens.map((item) => ({ ...item, statusId: 3, processedByNIP: '1', processedAt: '2026-10-30T00:00:00.000Z' })));
assert.ok(syncVehicleApprovalTokens(tokens, 4, '2', '2026-10-30T00:00:00.000Z').every((item) => item.statusId === 4));
assert.match(valid, /^[a-f0-9]{48}$/i);
assert.doesNotMatch('bad-token', /^[a-f0-9]{48}$/i);
assert.deepEqual(JSON.parse(JSON.stringify({ travelId: 'T.0377.1', qrToken: valid })), { travelId: 'T.0377.1', qrToken: valid });
assert.equal(plannedTravelDateTime('2026-11-03', '07:00'), '2026-11-03 07:00:00');
assert.equal(plannedTravelDateTime('2026-11-03', 'invalid'), '2026-11-03');
assert.equal(readFileSync(new URL('./travelModel.js', import.meta.url), 'utf8').includes("return { status: 'already_departed' }"), true);
assert.equal(isTravelQrAvailable({ EndDate: null, Remark: JSON.stringify({ qrToken: valid }) }, valid), true);
assert.equal(isTravelQrAvailable({ EndDate: '2026-11-03', Remark: JSON.stringify({ qrToken: valid }) }, valid), false);
assert.equal(isTravelQrAvailable({ EndDate: null, Remark: JSON.stringify({ qrToken: valid, departureAt: '2026-11-03T07:30:00.000Z' }) }, valid), false);
assert.equal(isTravelQrAvailable({ EndDate: null, CheckpointReturnedDate: '2026-11-03', Remark: JSON.stringify({ qrToken: valid }) }, valid), false);
assert.equal(isTravelQrReadable({ EndDate: null, CheckpointReturnedDate: null, Remark: JSON.stringify({ qrToken: valid, departureAt: '2026-11-03T07:30:00.000Z' }) }, valid), true);
assert.equal(typeof autoCloseTravels, 'function');
const travelModelSource = readFileSync(new URL('./travelModel.js', import.meta.url), 'utf8');
assert.match(travelModelSource, /AND \(@Level <> 1 OR NIP = @NIP\)/);
assert.match(travelModelSource, /new sql\.Transaction\(conn\)/);
assert.doesNotMatch(travelModelSource, /appLink|Aplikasi: \$\{appLink\}/);
assert.match(travelModelSource, /formatTravelApprovalMessage/);
assert.match(travelModelSource, /DriverName = CASE WHEN @StatusId = 3 THEN @DriverName ELSE DriverName END/);
const cutiModelSource = readFileSync(new URL('./cutiModel.js', import.meta.url), 'utf8');
assert.match(cutiModelSource, /FROM hris_GetTopLevel\(@NIP\)[\s\S]*ORDER BY a\.JobSeq DESC/);
console.log('travel model QR self-check passed');
